public class Literals {
    // Literals-it is a constant value which can be assigned to the variable.
    public static void main(String[] args) {
        byte age = 20; // integer literal
        char ch = 'A';// character literal
        float cgpa = 8.5f;//float literal
        double d1 = 9.999d;//double literal
        String name = "Arpita";//string literal

        System.out.println(name + age + ch + cgpa + d1 );

    }
    
}
