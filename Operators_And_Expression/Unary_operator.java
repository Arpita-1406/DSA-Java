package Operators_And_Expression;

public class Unary_operator {
    public static void main(String[] args) {
        
        int result1 = 2 + 3 * 4;     
         int result2 = (2 + 3) * 4;   
         int result3 = result2--;
         int result4 = ++result1;


System.out.println(result1);
System.out.println(result2);
System.out.println(result3);
System.out.println(result4);
    }
}
