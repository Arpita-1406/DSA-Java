package Strings;
//Escape sequence characters in Java are special characters used inside strings to perform special formatting actions like new line, tab, quotes, etc.
//They start with a backslash \.
//They improve output formatting.
public class escape_sequence {
    public static void main(String[] args) {

// 1.New Line(\n)
        System.out.println("Hello\nJava");
        
// 2. Tab Space(\t)
        System.out.println("Java\tProgramming");

// 3. Double Quote(\")
        System.out.println("\"Java\"");

// 4. Single Quote(\')
        System.out.println("\'A\'");

// 5. Backslash(\\)
        System.out.println("Hello\\Java");




    }
    
}
