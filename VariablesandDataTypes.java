// Variables and Data Types
// 1. Variable:-A variable is a named memory location used to store data. The value stored in a variable can change during program execution.

// 2. Data Types:-A data type specifies the kind of value a variable can hold.

// Data Types 
//  data types are divided into 2 categories:

// 1. Primitive Data Types
// DataType	 Size	   Example
// byte	     1 byte	    byte a = 10;
// short     2 bytes	short b = 1000;
// int	     4 bytes	int c = 50000;
// long	     8 bytes	long d = 100000L;
// float     4 bytes	float e = 5.5f;
// double    8 bytes	double f = 99.99;
// char	     2 bytes	char g = 'A';
// boolean   1 bit	    boolean h = true;

// 2. Non-Primitive Data Types

// These are created by the programmer or provided by Java.

// Examples:

// String
// Array
// Class
// Object
// Interface


